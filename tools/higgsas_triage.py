"""Triage of an asset library of Blender geometry node groups (Higgsas Geo Nodes) against MiniHou's node set.

    python3 -c "import bpy"                              # needs the bpy module (pip install bpy)
    python3 tools/higgsas_dump.py   Library.blend        # writes groups.json next to the cwd
    python3 tools/higgsas_triage.py groups.json          # reads tools/higgsas_verdicts.txt, writes docs/HIGGSAS_NODES.md

The verdicts are by hand (tools/higgsas_verdicts.txt): HAVE, PART(ly), NATIVE, LIB, FN or SKIP, a priority 1-3 and a note.
"""
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOCKET = {"NodeSocketGeometry": "geo", "NodeSocketFloat": "float", "NodeSocketInt": "int", "NodeSocketBool": "bool", "NodeSocketVector": "vec",
          "NodeSocketColor": "color", "NodeSocketString": "str", "NodeSocketObject": "object", "NodeSocketImage": "image", "NodeSocketMenu": "menu",
          "NodeSocketRotation": "rot", "NodeSocketMatrix": "matrix", "NodeSocketMaterial": "material", "NodeSocketCollection": "collection"}
LABEL = {"HAVE": "have it", "PART": "partly there", "NATIVE": "build natively", "LIB": "library node", "FN": "wrangle function", "SKIP": "not applicable"}


def load_verdicts():
    out = {}
    for line in (ROOT / "tools" / "higgsas_verdicts.txt").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, code, prio, note = [p.strip() for p in line.split("|", 3)]
        out[name] = (code, prio, note)
    return out


def sockets(items):
    return ", ".join(f"{s['name']}:{SOCKET.get(s['type'], s['type'][12:].lower())}" for s in items if s["type"] != "NodeSocketMenu")


def main(path):
    groups = [g for g in json.load(open(path, encoding="utf-8")) if g.get("asset")]
    verdicts = load_verdicts()
    missing = [g["name"] for g in groups if g["name"] not in verdicts]
    if missing:
        sys.exit("no verdict for: " + ", ".join(missing))
    counts = collections.Counter(verdicts[g["name"]][0] for g in groups)
    L = ["# Higgsas Geo Nodes against MiniHou", "",
         f"{len(groups)} asset node groups from the library (Blender 5.0 file), each compared with MiniHou's nodes. Generated by `tools/higgsas_triage.py` from "
         "`tools/higgsas_verdicts.txt`; the verdicts are hand-made, from each group's sockets, size and the Blender nodes inside it.", "",
         "| verdict | count | meaning |", "|---|---|---|"]
    meaning = {"HAVE": "MiniHou already has an equivalent node", "PART": "covered in part: the note says what is missing",
               "NATIVE": "worth building into the engine (topology work, speed, or one node replacing several)",
               "LIB": "a library node (`nodes/*.py`) is enough: parametric shapes, small solvers, art-directed tools",
               "FN": "not a node: a wrangle function or a one-line snippet (field maths, geometry helpers)",
               "SKIP": "does not apply (Blender cameras, image textures, debug overlays)"}
    for c in ("HAVE", "PART", "NATIVE", "LIB", "FN", "SKIP"):
        L.append(f"| {LABEL[c]} | {counts[c]} | {meaning[c]} |")
    L += ["", "## What the library mostly is", "",
          "Most groups are Blender *fields*: they take a position or an index and give a value (falloffs, selections, noise, linear algebra), and they chain 2-3 thousand "
          "Math nodes between them. MiniHou has no field graph; the same job is a point attribute, a group, or a wrangle expression. So those become one native node that writes "
          "an attribute (`falloff`), or a wrangle function (`curlnoise`, `ease`, `gauss`), not 30 nodes.", ""]
    L += ["## Build list", "", "Priority 1 first. Where several groups say the same node, they are listed together.", ""]
    merged = collections.OrderedDict()
    for g in groups:
        c, p, note = verdicts[g["name"]]
        if c not in ("NATIVE",):
            continue
        key = note.split("::")[0].strip()
        merged.setdefault(key, {"prio": p, "names": [], "notes": []})
        merged[key]["notes"].append(note.split("::", 1)[1].strip())
        merged[key]["names"].append(g["name"])
        merged[key]["prio"] = min(merged[key]["prio"], p)
    L += ["### Native nodes", "", "| priority | MiniHou node | replaces | why |", "|---|---|---|---|"]
    for key, v in sorted(merged.items(), key=lambda kv: (kv[1]["prio"], kv[0])):
        L.append(f"| {v['prio']} | `{key}` | {', '.join(v['names'])} | {max(v['notes'], key=len)} |")
    lib = [(verdicts[g["name"]][1], g["name"], verdicts[g["name"]][2]) for g in groups if verdicts[g["name"]][0] == "LIB"]
    L += ["", "### Library nodes (priority 1-2)", "", "| priority | group | note |", "|---|---|---|"]
    for p, n, note in sorted(lib):
        if p in ("1", "2"):
            L.append(f"| {p} | {n} | {note} |")
    L += ["", f"The other {sum(1 for p, _, _ in lib if p == '3')} library candidates are priority 3: see the tables below.", ""]
    L += ["## By catalog", ""]
    cats = collections.OrderedDict()
    for g in sorted(groups, key=lambda g: (g.get("catalog", ""), g["name"])):
        cats.setdefault(g.get("catalog", "").replace("Higgsas Nodes-", "") or "(none)", []).append(g)
    for cat, items in cats.items():
        L += [f"### {cat}", "", "| group | inputs -> outputs | verdict | note |", "|---|---|---|---|"]
        for g in items:
            c, p, note = verdicts[g["name"]]
            sig = f"{sockets(g['in'])} -> {sockets(g['out'])}".replace("|", "/")
            L.append(f"| {g['name']} | {sig} | {LABEL[c]}{' ' + p if p else ''} | {note.replace('|', '/')} |")
        L.append("")
    (ROOT / "docs" / "HIGGSAS_NODES.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote docs/HIGGSAS_NODES.md", dict(counts))


if __name__ == "__main__":
    main(sys.argv[1])
